# ── 정규화·분리 ────────────────────────────────────────────────────
_SENT = re.compile(r"[.!?\n·…]+|\s{2,}|(?<=다)\s+(?=[가-힣])")
_QUANT = re.compile(r"\d+\s*(" + "|".join(map(re.escape, sorted(QUANT_UNITS, key=len, reverse=True))) + r")")
_HANGUL = re.compile(r"[가-힣]")
_LETTER = re.compile(r"[A-Za-z가-힣]")
_REPEAT = re.compile(r"(.)\1{2,}")           # 같은 글자 3번 이상 → 2번
_MONEY = re.compile(r"\d\s*(만\s*)?원")        # 금액 — 가격 축의 속성(18,000원 · 4만 원)
_MONEY_WORDS = {"만원", "천원", "만 원", "천 원"}

#: `language()` 의 값. 한글 비중 30% 미만이면 사전으로 잴 수 없는 글이다.
KO, FOREIGN, NON_TEXT = "ko", "foreign", "non_text"


def normalize(text: str | None) -> str:
    """(4) 매칭용 정규화. 원문은 건드리지 않고 판정에만 쓴다."""
    t = unicodedata.normalize("NFKC", text or "").lower()
    return _REPEAT.sub(r"\1\1", t)


def language(text: str | None) -> str:
    """한글 비중으로 한국어 글인지 본다. 외국어·이모지만인 글은 사전이 못 재는 것이지 빈 글이 아니다."""
    letters = _LETTER.findall(text or "")
    if not letters:
        return NON_TEXT
    ko = sum(1 for c in letters if _HANGUL.match(c))
    return KO if ko / len(letters) >= 0.3 else FOREIGN


def _forms(vocab: list[str]) -> dict[str, str]:
    """매칭 꼴 → 사전 원형. '실하' 는 '실해·실한·실함·실했' 로도 걸린다(하-불규칙 활용)."""
    out: dict[str, str] = {}
    for w in vocab:
        out.setdefault(w, w)
        if w.endswith("하"):
            for tail in ("해", "한", "함", "했"):
                out.setdefault(w[:-1] + tail, w)
    return out


def _stem(word: str) -> str:
    """(1) 어근 — 공백을 뺀 앞 두 글자. '느끼'·'느끼하'·'느끼함' 이 한 속성이 된다."""
    return word.replace(" ", "")[:2]


_LEX_F = {c: {k: _forms(v) for k, v in d.items()} for c, d in LEX.items()}
_SIG_F = {name: _forms(v) for name, v in
          (("degree", DEGREE), ("compare", COMPARE), ("referent", REFERENT), ("reason", REASON))}


def _hits(text: str, forms: dict[str, str]) -> list[str]:
    """`text` 에 나온 사전 원형들 — 어근이 같으면 하나로. 함정어 안에서만 나오면 무시."""
    found: dict[str, str] = {}
    for form, base in forms.items():
        if form not in text:
            continue
        traps = TRAPS.get(form) or TRAPS.get(base)
        # 함정어 한 번이 어휘를 **몇 번** 먹는지까지 센다. "빵빵" 은 '빵' 을 둘 삼키므로
        # 개수만 비교하면("빵" 2회 vs "빵빵" 1회) 함정을 빠져나간다. 반대로 함정어가
        # 그 활용형을 품고 있지 않으면(트랩은 원형에 달려 있다) 0 을 먹어 멀쩡한 매칭을
        # 죽이지 않는다 — '연하' 의 트랩이 '연해' 꼴까지 나열된 이유다.
        if traps and text.count(form) <= sum(tr.count(form) * text.count(tr) for tr in traps):
            continue
        found.setdefault(_stem(base), base)
    return sorted(found.values())


def score_sentence(sent: str) -> dict:
    """문장 하나에서 축별 레벨과 신호를 구한다. 입력은 이미 `normalize` 된 것."""
    sig = set()
    if _hits(sent, _SIG_F["degree"]) or _QUANT.search(sent):
        sig.add("degree")
    for name in ("compare", "referent", "reason"):
        if _hits(sent, _SIG_F[name]):
            sig.add(name)

    out = {}
    for c in CATEGORIES:
        attrs = _hits(sent, _LEX_F[c]["attr"])
        if c == "price" and _MONEY.search(sent):
            # 얼마인지 적었으면 가격의 속성을 말한 것이다. '만원'·'천원' 어휘는 같은 사실이라
            # 하나로 합친다 — 둘로 세면 multiattr 이 헛돈다("4만원" 이 속성 둘이 된다).
            attrs = sorted({"금액" if a in _MONEY_WORDS else a for a in attrs} | {"금액"})
        val = _hits(sent, _LEX_F[c]["valence"])
        top = _hits(sent, _LEX_F[c]["topic"])

        csig = set(sig)
        if len(attrs) >= 2:                      # 어근이 다른 속성 둘 이상
            csig.add("multiattr")

        # 대기·가격은 숫자 자체가 속성 정보다 (30분 웨이팅, 15000원)
        quantified = bool(_QUANT.search(sent)) and c in ("wait", "price")

        if attrs:
            lvl = 3 if len(csig) >= 2 else 2     # 속성어가 있어야만 L3 에 닿는다
        elif top and quantified:
            lvl = 2                              # 수량 명시는 L2 까지만
        elif (val or top) and len(csig) >= 2:
            lvl = 2                              # 속성어는 없지만 구체 신호가 충분한 경우
        elif val or top:
            lvl = 1
        else:
            lvl = 0
        out[c] = {"level": lvl, "attrs": attrs, "valence": val, "topic": top,
                  "signals": sorted(csig) if attrs else []}
    return out


def _empty(text: str, lang: str) -> dict:
    return {
        "levels": {c: 0 for c in CATEGORIES}, "grade": 0, "breadth": 0, "depth_sum": 0,
        "top_category": None, "attrs": {c: [] for c in CATEGORIES},
        "signals": {c: [] for c in CATEGORIES},
        "hangul_len": len(_HANGUL.findall(text or "")), "lang": lang,
    }


def score(text: str | None) -> dict:
    """리뷰 한 건의 표현력. 분석 판의 `score_review` 와 같은 모양에 `lang` 이 붙었다."""
    lang = language(text)
    if lang != KO:                               # (5) 못 잰 것이지 빈 것이 아니다
        return _empty(text or "", lang)
    norm = normalize(text)
    sents = [s.strip() for s in _SENT.split(norm) if s and s.strip()] or [norm]

    levels = {c: 0 for c in CATEGORIES}
    evidence = {c: {"attrs": set(), "signals": set()} for c in CATEGORIES}
    for s in sents:
        for c, r in score_sentence(s).items():
            if r["level"] > levels[c]:
                levels[c] = r["level"]
            evidence[c]["attrs"].update(r["attrs"])
            evidence[c]["signals"].update(r["signals"])

    grade = max(levels.values())
    return {
        "levels": levels,
        "grade": grade,
        "breadth": sum(1 for v in levels.values() if v >= 1),
        "depth_sum": sum(levels.values()),
        "top_category": max(CATEGORIES, key=lambda c: levels[c]) if grade else None,
        "attrs": {c: sorted(evidence[c]["attrs"]) for c in CATEGORIES},
        "signals": {c: sorted(evidence[c]["signals"]) for c in CATEGORIES},
        "hangul_len": len(_HANGUL.findall(text or "")),
        "lang": lang,
    }


score_review = score      # 분석 판 이름


def level_of(text: str | None, category: str) -> int:
    """한 축의 레벨(0~3). 설문 세 줄처럼 '이 줄은 이 축' 이 정해진 글에 쓴다."""
    if category not in LEX:
        raise KeyError(category)
    return score(text)["levels"][category]


def rank_key(text: str | None) -> tuple[int, int, int]:
    """정렬 키 — 클수록 표현력이 높다. (깊이, 합, 폭). `sorted(..., reverse=True)` 또는 음수로."""
    s = score(text)
    return s["grade"], s["depth_sum"], s["breadth"]
